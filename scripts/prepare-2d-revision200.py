"""Import generated complete sprites: trim transparent cells, register and pack.

No anatomy is assembled, deformed or generated by this build step. Source sheets
and prompts are retained in docs/2d-refinement/source200. Existing v4 stays intact.
"""
from pathlib import Path
import json, hashlib
import cv2
import numpy as np
from PIL import Image, ImageDraw

ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'docs/2d-refinement/source200'
ART=ROOT/'public/assets/visual'
OUT=ROOT/'docs/2d-refinement/qa/200/import'
OUT.mkdir(parents=True,exist_ok=True)
records=[]

def crop_cell(image,col,row,cols,rows):
    w,h=image.size
    cell=image.crop((round(col*w/cols),round(row*h/rows),round((col+1)*w/cols),round((row+1)*h/rows)))
    a=np.array(cell)
    # Alpha islands outside the main figure are generator debris, not anatomy.
    count,labels,stats,_=cv2.connectedComponentsWithStats((a[:,:,3]>40).astype('uint8'))
    main=1+np.argmax(stats[1:,cv2.CC_STAT_AREA])
    keep=(labels==main).astype('uint8')
    keep=cv2.dilate(keep,np.ones((3,3),np.uint8))
    a[:,:,3]=np.minimum(a[:,:,3],keep*255)
    cell=Image.fromarray(a)
    return cell.crop(cell.getbbox())

def record(path):
    records.append({'file':path.relative_to(ROOT).as_posix(),'bytes':path.stat().st_size,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})

for sex in ['male','female']:
    generated=Image.open(SRC/f'heads-{sex}.png').convert('RGBA')
    for cls,neck in {'warrior':68,'hunter':62,'astral':57,'xenobinder':58}.items():
        old=Image.open(ART/f'customization/heads-{cls}-{sex}.png').convert('RGBA')
        oldmask=Image.open(ART/f'customization/masks-{cls}-{sex}.png').convert('RGBA')
        heads=Image.new('RGBA',(640,480));heads.paste(old,(0,0))
        masks=Image.new('RGBA',(640,480));masks.paste(oldmask,(0,0))
        for row in range(2):
            for col in range(8):
                piece=crop_cell(generated,col,row,8,2)
                # Common skull-to-neck height, aspect ratio preserved.
                height=neck-19
                fitted=piece.resize((round(piece.width*height/piece.height),height),Image.Resampling.LANCZOS)
                tile=Image.new('RGBA',(80,80));tile.alpha_composite(fitted,((80-fitted.width)//2,19))
                rgba=np.array(tile);rgb=rgba[:,:,:3].astype(float);alpha=rgba[:,:,3]>40
                yy,xx=np.mgrid[:80,:80]
                r,g,b=[rgb[:,:,i] for i in range(3)]
                # New heads use brown hair + warm skin, classified before palette bake.
                skin=alpha&(r>g*1.13)&(g>b*1.08)&(r>95)&(yy>19+height*.40)
                if col in [3,4,5]:skin=alpha&(yy>19+height*.78)&(r>g*1.13)&(r>95)
                hair=alpha&~skin
                semantic=np.zeros_like(rgba);semantic[:,:,0]=hair*255;semantic[:,:,1]=skin*255;semantic[:,:,3]=rgba[:,:,3]
                heads.paste(tile,(col*80,(4+row)*80));masks.paste(Image.fromarray(semantic),(col*80,(4+row)*80))
        for prefix,img in [('heads',heads),('masks',masks)]:
            path=ART/f'customization/{prefix}-{cls}-{sex}-v2.png';img.save(path,optimize=True);record(path)

    generated=Image.open(SRC/f'warrior-side-{sex}.png').convert('RGBA')
    attacks=Image.open(SRC/f'warrior-action-{sex}.png').convert('RGBA')
    for outfit,style in enumerate(['none','basic','reinforced']):
        atlas=Image.open(ART/f'complete-actors/warrior-{sex}-{style}-motion-v4.png').convert('RGBA')
        for direction in range(8):
            piece=crop_cell(attacks,direction,outfit,8,3)
            height=164
            fitted=piece.resize((round(piece.width*height/piece.height),height),Image.Resampling.LANCZOS)
            tile=Image.new('RGBA',(192,192));tile.alpha_composite(fitted,((192-fitted.width)//2,183-height))
            frame=direction*4+3
            atlas.paste(tile,(frame%8*192,frame//8*192))
        for facing,row in [(0,2),(1,6)]:
            for phase in range(4):
                piece=crop_cell(generated,phase+facing*4,outfit,8,3)
                # Full figure stays continuous. Register skull and floor, not its weapon.
                height=164
                fitted=piece.resize((round(piece.width*height/piece.height),height),Image.Resampling.LANCZOS)
                tile=Image.new('RGBA',(192,192));tile.alpha_composite(fitted,((192-fitted.width)//2,183-height))
                frame=40+row*4+phase
                atlas.paste(tile,(frame%8*192,frame//8*192))
        path=ART/f'complete-actors/warrior-{sex}-{style}-motion-v5.png';atlas.save(path,optimize=True);record(path)

(OUT/'report.json').write_text(json.dumps({'method':'Complete generated side-walk paintings, alpha trim and uniform registration; two original eight-view haircuts per body; old sources unchanged.','assets':records},indent=2)+'\n',encoding='utf8')
print('Imported',len(records),'atlases; bytes',sum(r['bytes'] for r in records))
