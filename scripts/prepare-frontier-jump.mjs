// Bake the reference clip's authored vertical lift once, outside the game loop.
// Physics supplies world height. The paired animation track cancels only the
// extra lift embedded in the original clip, preserving the full skeletal pose.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import * as T from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
const bytes=await readFile('public/assets/frontier-3d/explorer.glb');
const g=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
const model=g.scene,bounds=new T.Box3().setFromObject(model,true),height=bounds.getSize(new T.Vector3()).y;
const mixer=new T.AnimationMixer(model),clip=g.animations.find(c=>c.name==='Jump');
if(!clip)throw Error('Missing Jump reference clip');
const action=mixer.clipAction(clip);action.setLoop(T.LoopOnce,1);action.clampWhenFinished=true;action.play();
const samples=[];let last=0;
for(let i=0;i<=Math.ceil(clip.duration*60);i++){
 const time=Math.min(i/60,clip.duration);mixer.update(time-last);last=time;model.updateMatrixWorld(true);
 const box=new T.Box3().setFromObject(model,true),lift=Math.max(0,box.min.y-bounds.min.y)/height;
 samples.push([Number(time.toFixed(7)),Number(lift.toFixed(7))]);
}
const source=createHash('sha256').update(bytes).digest('hex');
await writeFile('src/experiments/frontier-3d/jumpLift.ts',`// Generated by scripts/prepare-frontier-jump.mjs from the unchanged explorer.glb.\n// Source SHA256: ${source}\n// [clip seconds, authored foot lift / reference height]; no per-frame vertex scan.\nexport const jumpLift:readonly (readonly [number,number])[]=${JSON.stringify(samples)};\n`);
console.log('Baked',samples.length,'samples;',clip.duration,'seconds; source',source);
